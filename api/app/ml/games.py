"""
Карта управляющих осей по типу игры.

Признаки движения считаются по той оси, которой пациент управляет в игре.
- game1 (Space Catcher) — наклон кисти влево/вправо = roll
- game2 (City Driver)   — руление наклоном кисти = roll (руль) + наклон вперёд/назад = pitch (газ/тормоз)

ПЕРВИЧНАЯ ось (`GAME_AXIS`) — на ней работает модель аномалий, нарратив и рекомендации
(модель обучена на одной оси). ВТОРИЧНЫЕ оси (`SECONDARY_AXES`) считаются тем же
`extract_features`, отдаются в дашборд как дополнительная картина движения, но в модель
НЕ подаются. Когда модель переобучат на объединённом векторе — вторичную ось можно поднять
в первичную здесь же, без правок роутов.

Если в будущем появится игра на pitch (сгибание/разгибание кисти), достаточно
добавить запись сюда — роуты sessions/insights подхватят ось автоматически.
"""

GAME_AXIS = {
    "game1": "r",
    "game2": "r",
}

DEFAULT_AXIS = "r"

# Дополнительные оси управления по игре: {ось: человекочитаемая подпись}.
# Считаются параллельно первичной оси и показываются врачу, в модель аномалий не идут.
SECONDARY_AXES = {
    "game2": {"p": "Газ/тормоз (наклон вперёд/назад)"},
}


def axis_for_game(game_type: str) -> str:
    return GAME_AXIS.get(game_type, DEFAULT_AXIS)


def secondary_axes_for_game(game_type: str) -> dict:
    """Вторичные оси игры: {ось: подпись}. Пусто, если игра одноосевая."""
    return SECONDARY_AXES.get(game_type, {})
